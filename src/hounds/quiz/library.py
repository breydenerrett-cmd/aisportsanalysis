"""The hound quiz's library: named strategy ideas, and the answer tables the quiz is built from.

WHAT IT IS
----------
`config/hounds_archetypes.json` holds, as data:

  archetypes      40+ named, fun strategy ideas ("Revenge Tour", "Windy Overs", "Chalk Eater"...). Each carries the
                  EXACT spec fragment (a list of version-2 rules, optionally a ranking rule) the real builder accepts.
  personalities   the six temperaments the quiz offers; each is a recipe per kind of market (ml, total, prop).
  markets, price_comforts, quirks, timings, looks, name_pools   the other answer tables.

NOTHING IN THE FILE IS PROSE ABOUT WHAT A RULE DOES. The plain-English description shown beside every archetype is
GENERATED from its fragment by `src/hounds/english/render.py`, the same renderer that writes a saved dog's published
rules, so a card can never say one thing while the engine does another. `validate_library()` pushes every fragment
through the real validator (`user_spec.validate_spec`), so an archetype the builder would refuse cannot ship; a test runs it.

THE HARD LINES LIVE HERE TOO. No price band reaches -200 (the validator refuses it anyway), the copy makes no claim of
profit or edge, and the library says outright that no archetype is known to win.

Pure functions over one JSON file: no network, no clock, and nothing here touches a ledger. Python 3.10-compatible.
"""

from __future__ import annotations

import copy
import json
import re
from pathlib import Path
from typing import Any, Mapping, Optional

from src import paths
from src.hounds import user_rules as R
from src.hounds import user_spec
from src.hounds.english import render

CONFIG_NAME = "hounds_archetypes.json"
PICK_LIMIT = 3                    # how many archetype cards a quiz may pick
PLACEHOLDER_NAME = "Quiz Pup"     # a fragment is validated under this name; the real name comes from compose
HONESTY_LINE = ("Fun rules, graded in public on paper. A hound is a rule, not a prediction, and none of these is "
                "known to win.")

# copy that would make a claim (docs/VOICE.md): none of it belongs in a pitch, a name or a tagline
CLAIM_PATTERNS = (r"\block\b", r"\blocks\b", r"guarantee", r"can'?t lose", r"sure thing", r"free money", r"\bedge\b",
                  r"\bev\b", r"expected value", r"\bprofit", r"\bwinning strategy\b", r"\bbeats? the (book|market)")
ICON_KEYS = frozenset("""
flame moon wave target hourglass road house bolt crown wind coin letters stars football plus bone gremlin tv snow sun
rain plane calendar key kick feather rocket twins chart paw cloud trophy ruler updown bat dice scale anchor sunrise clock
""".split())
KINDS = ("ml", "total", "prop")
STANCES = ("dog", "chalk", "neutral")


class LibraryError(ValueError):
    """The library file has problems. `problems` lists every one."""

    def __init__(self, problems):
        self.problems = list(problems)
        super().__init__("; ".join(self.problems[:6]))


_cache: dict = {}


def config_path() -> Path:
    return Path(paths.repo_root()) / "config" / CONFIG_NAME


def load(path: Optional[Path] = None) -> dict:
    """The parsed library, cached per file modification time. Treat it as read-only (use `copy.deepcopy` to edit)."""
    p = Path(path) if path else config_path()
    stamp = (str(p), p.stat().st_mtime_ns)
    hit = _cache.get("lib")
    if hit and hit[0] == stamp:
        return hit[1]
    lib = json.loads(p.read_text(encoding="utf-8"))
    _cache["lib"] = (stamp, lib)
    return lib


def by_id(rows) -> dict:
    return {row["id"]: row for row in rows}


# ---------------------------------------------------------------------------
# fragments -> specs -> English
# ---------------------------------------------------------------------------

def draft_spec(fragment: Mapping, *, name: str = PLACEHOLDER_NAME, **over: Any) -> dict:
    """A complete version-2 spec dict (not yet validated) for a fragment: the fragment's rules plus its optional
    ranking rule and bet cap, over the menu's defaults."""
    spec = {"version": user_spec.SPEC_VERSION_V2, "name": name, "tagline": "",
            "rules": copy.deepcopy(list(fragment["rules"]))}
    for key in ("rank_by", "max_bets_per_day", "stake_units", "lock_minutes"):
        if key in fragment:
            spec[key] = fragment[key]
    spec.update(over)
    return spec


def validate_fragment(fragment: Mapping, *, name: str = PLACEHOLDER_NAME) -> dict:
    """The fragment as a normalised spec, or `user_spec.SpecError` listing every problem."""
    return user_spec.validate_spec(draft_spec(fragment, name=name))


def english_for(fragment: Mapping) -> dict:
    """{'sentences': [one per rule], 'text': 'them joined'}: generated by the renderer from the validated fragment."""
    spec = validate_fragment(fragment)
    sentences = render.rule_sentences(spec)
    return {"sentences": sentences, "text": " ".join(sentences)}


# ---------------------------------------------------------------------------
# checks (the tests call these; so does the API's startup-free path, never at request time)
# ---------------------------------------------------------------------------

def _claim_problem(text: str) -> Optional[str]:
    low = text.lower()
    for pat in CLAIM_PATTERNS:
        if re.search(pat, low):
            return pat
    return None


def validate_library(lib: Optional[Mapping] = None) -> list:
    """Every problem in the library, as plain strings (empty when it is sound)."""
    lib = lib if lib is not None else load()
    problems: list = []

    def check_copy(where: str, text: Any, limit: int) -> None:
        if not isinstance(text, str) or not text.strip():
            problems.append(f"{where}: needs text")
            return
        if len(text) > limit:
            problems.append(f"{where}: {len(text)} characters, the limit is {limit}")
        bad = _claim_problem(text)
        if bad:
            problems.append(f"{where}: makes a claim ({bad})")
        if re.search(r"[^\x20-\x7e]", text):
            problems.append(f"{where}: only plain ASCII in copy (no emoji)")

    seen: set = set()
    archetypes = lib.get("archetypes") or []
    if len(archetypes) < 30:
        problems.append(f"archetypes: {len(archetypes)} found, the library promises 30 or more")
    for a in archetypes:
        aid = a.get("id", "?")
        if aid in seen:
            problems.append(f"{aid}: duplicate id")
        seen.add(aid)
        check_copy(f"{aid}.name", a.get("name"), user_spec.NAME_MAX + 6)
        check_copy(f"{aid}.pitch", a.get("pitch"), 130)
        if a.get("icon") not in ICON_KEYS:
            problems.append(f"{aid}: unknown icon {a.get('icon')!r}")
        if a.get("stance") not in STANCES:
            problems.append(f"{aid}: stance must be one of {STANCES}")
        if not set(a.get("kinds") or []) <= set(KINDS) or not a.get("kinds"):
            problems.append(f"{aid}: kinds must be some of {KINDS}")
        if not a.get("works_in") or not set(a["works_in"]) <= set(user_spec.SPORTS):
            problems.append(f"{aid}: works_in must be some of {user_spec.SPORTS}")
        frag = a.get("fragment")
        if not isinstance(frag, Mapping) or not frag.get("rules"):
            problems.append(f"{aid}: needs a fragment with rules")
            continue
        try:
            spec = validate_fragment(frag)
        except user_spec.SpecError as exc:
            problems.append(f"{aid}: the builder refuses it ({exc})")
            continue
        for rule in spec["rules"]:
            if rule["price_min"] < user_spec.SHORTEST_ALLOWED_PRICE and rule["price_min"] < 0:
                problems.append(f"{aid}: price reaches {user_spec.MAX_FAVOURITE_PRICE}")
            if not set(rule["sports"]) <= set(a["works_in"]):
                problems.append(f"{aid}: a rule covers sports outside works_in")
        if set(frag.get("rank_by") and [frag["rank_by"]] or []) - set(R.RANK_RULES):
            problems.append(f"{aid}: unknown rank_by")
    for table in ("personalities", "markets", "price_comforts", "quirks", "timings"):
        ids = [row.get("id") for row in lib.get(table) or []]
        if not ids or len(set(ids)) != len(ids):
            problems.append(f"{table}: needs unique ids")
        for row in lib.get(table) or []:
            check_copy(f"{table}.{row.get('id')}.name", row.get("name"), 60)
            check_copy(f"{table}.{row.get('id')}.pitch", row.get("pitch"), 130)
            if row.get("icon") not in ICON_KEYS:
                problems.append(f"{table}.{row.get('id')}: unknown icon {row.get('icon')!r}")
    for p in lib.get("personalities") or []:
        for kind in KINDS:
            recipe = (p.get("recipes") or {}).get(kind)
            if not recipe:
                problems.append(f"personality {p.get('id')}: no {kind} recipe")
        if p.get("color") not in R.COLOR_IDS or p.get("badge") not in R.BADGE_IDS:
            problems.append(f"personality {p.get('id')}: colour or badge off the menu")
        if p.get("rank_by") not in R.RANK_RULES:
            problems.append(f"personality {p.get('id')}: unknown rank_by")
    for c in lib.get("price_comforts") or []:
        if c["price_min"] < user_spec.SHORTEST_ALLOWED_PRICE and c["price_min"] < 0:
            problems.append(f"price comfort {c['id']}: reaches {user_spec.MAX_FAVOURITE_PRICE}")
    return problems


