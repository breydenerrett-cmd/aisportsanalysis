def public_archetype(a: Mapping) -> dict:
    spec = validate_fragment(a["fragment"])
    sentences = render.rule_sentences(spec)
    works = fit.resolve_sports(a["works_in"])
    return {"id": a["id"], "name": a["name"], "pitch": a["pitch"], "short": a["short"], "icon": a["icon"],
            "stance": a["stance"], "tags": list(a.get("tags") or []), "works_in": works,
            "works_any": set(works) == set(user_spec.SPORTS), "kinds": list(a["kinds"]),
            "has_generic": bool(a.get("generic")),
            "rule_count": len(spec["rules"]), "spec_fragment": copy.deepcopy(a["fragment"]),
            "english": " ".join(sentences), "sentences": sentences}


def archetypes(lib: Optional[Mapping] = None) -> list:
    lib = lib if lib is not None else load()
    return [public_archetype(a) for a in lib["archetypes"]]


def _plain(row: Mapping, *drop: str) -> dict:
    return {k: copy.deepcopy(v) for k, v in row.items() if k not in drop}


def public_library(lib: Optional[Mapping] = None) -> dict:
    """GET /hounds/quiz/library: every answer table, the archetypes with their generated English, and the limits."""
    lib = lib if lib is not None else load()
    return {
        "version": lib.get("version", 1),
        "paper_only": True, "not_advice": user_spec.NOT_ADVICE, "honesty": HONESTY_LINE,
        "price_cap_note": f"No selection at {user_spec.MAX_FAVOURITE_PRICE} or worse, ever.",
        "limits": {"archetype_picks": PICK_LIMIT, "max_rules": R.MAX_RULES,
                   "bets_per_day": list(user_spec.MAX_BETS_RANGE), "stake_units": list(R.STAKE_CHOICES)},
        "sports": sport_choices(lib),
        "sports_any": any_sport_choice(lib),
        "sports_default": list(user_spec.LEGACY_SPORTS),
        "archetypes": archetypes(lib),
        "personalities": [_plain(p, "recipes") for p in lib["personalities"]],
        "markets": [_plain(m, "markets") | {"markets": list(m["markets"])} for m in lib["markets"]],
        "price_comforts": [_plain(c) for c in lib["price_comforts"]],
        "quirks": [{**_plain(q, "condition"), "english": render_condition(q)} for q in lib["quirks"]],
        "timings": [_plain(t) for t in lib["timings"]],
        "looks": copy.deepcopy(lib["looks"]),
        "weekdays": [{"value": v, "label": label} for v, label in R.WEEKDAYS],
    }


def render_condition(quirk: Mapping) -> str:
    """The quirk's condition as the renderer words it (so a quirk card shows exactly what it will do)."""
    kind = "ml_spread" if "ml" in quirk["kinds"] else ("total" if "total" in quirk["kinds"] else "prop")
    try:
        return R.condition_text(quirk["condition"], kind)
    except (KeyError, TypeError):
        return ""
