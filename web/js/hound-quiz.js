// ---- the draft (localStorage, every touch guarded) ------------------------------------------------------------------

function storage() {
  try { return window.localStorage || null; } catch (err) { return null; }
}

export function readDraft() {
  try {
    const ls = storage();
    const raw = ls && ls.getItem(DRAFT_KEY);
    if (!raw) return null;
    const d = JSON.parse(raw);
    return d && d.v === 1 && d.answers && typeof d.answers === "object" ? d : null;
  } catch (err) { return null; }
}

function persist() {
  try {
    const ls = storage();
    if (!ls) return;
    if (!hasAnyAnswer() && !S.english.text && !S.nameTouched) { ls.removeItem(DRAFT_KEY); return; }
    ls.setItem(DRAFT_KEY, JSON.stringify({ v: 1, answers: S.answers, step: S.step, stage: S.stage === "reveal" ? "reveal" : "quiz",
      name: S.nameTouched ? S.name : "", tagline: S.tagline, english: { text: S.english.text, draft: S.english.draft },
      pendingSave: S.pendingSave, savedAt: Date.now() }));
  } catch (err) { /* a full or blocked store: no resume, nothing else */ }
}

function clearDraft() {
  try { const ls = storage(); if (ls) ls.removeItem(DRAFT_KEY); } catch (err) { /* nothing to clear */ }
}

function restore(d) {
  const base = blankAnswers();
  const a = d.answers || {};
  for (const k of Object.keys(base)) if (a[k] !== undefined && a[k] !== null) base[k] = a[k];
  base.look = Object.assign({ coat: null, accessory: null }, a.look || {});
  S.answers = base;
  S.step = Number.isInteger(d.step) && d.step >= 0 && d.step < STEPS.length ? d.step : 0;
  S.name = typeof d.name === "string" ? d.name : "";
  S.nameTouched = !!S.name;
  S.tagline = typeof d.tagline === "string" ? d.tagline : "";
  const e = d.english || {};
  S.english = { text: typeof e.text === "string" ? e.text : "", draft: e.draft && typeof e.draft === "object" ? e.draft : null,
    understood: [], notRead: [], assumed: [] };
  S.pendingSave = !!d.pendingSave;
}

