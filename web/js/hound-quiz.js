/**
 * web/quiz.html: the hound quiz.
 *
 * FOUR STEPS, THEN A REVEAL (owner ruling 2026-10-21, "fewer steps and simpler ... the hound is the foundation"). The quiz used to be eight
 * questions (sports, markets, personality, risk, timing, moves, quirks, look). It is now four:
 *
 *   1 sports (chips, with an "All sports" chip; the popular ones first, the rest behind More)
 *   2 style (the personalities, four to a page, "Show me others" turns the page; Gematria and Mystic are among them)
 *   3 risk (ONE three-way choice, safest to boldest. It maps to a price band, a stake and a bets-a-day cap; the table is
 *     `risk_levels` in config/hounds_archetypes.json, served by GET /hounds/quiz/library, so the page owns no number)
 *   4 name and look (a name box and a coat and accessory; both optional, the hound is drawn big and follows every pick)
 *
 * Every field the quiz no longer asks for falls to a default derived from those four: the markets default to moneylines, the timing to the
 * server's default lock, the base rule to the personality's own, no quirks, no extra move cards. Every one of those is still a choice in the
 * builder ("Edit rules" on the reveal hands the draft over), so nothing was taken away, only moved off the first-run path.
 *
 * THE PAGE OWNS NO RULE. Every card comes from `GET /hounds/quiz/library` (config/hounds_archetypes.json), and the answers become a spec
 * through `POST /hounds/quiz/compose` (src/hounds/quiz/compose.py), which resolves conflicts, merges the English box and runs the real
 * validator. The plain English under every rule card is generated by the server's renderer from the spec, so the page cannot describe a
 * rule the engine does not run. This file only draws what came back.
 *
 * THE REVEAL shows the hound with a celebrate pose, a name (three suggestions, editable), the rules as cards, any warnings,
 * "Would have bet today" (POST /hounds/builder/preview, read-only), "Backtest this" (POST /hounds/drill, signed in, labelled
 * hindsight and never counted), a box for anything in the person's own words (POST /hounds/english, then composed in as extra
 * rules), "Edit rules" (hands the spec to the builder) and "Keep {Name}" (the builder's own save door, POST /hounds).
 *
 * SIGNED OUT. Everything up to the last button works without an account. Once the hound has been built, named and has met today's
 * board, a "Keep {Name}" form appears under the picks (web/js/keep.js): an email, a password and the "I am 21 or older" box. One
 * submit makes a free account (POST /auth/signup), signs the person in and saves this hound, on this page, with no redirect.
 * The record starts at the keep; nothing is backfilled. The whole quiz also stays in localStorage (every access wrapped in
 * try/catch: a blocked store only means no resume), so a person who would rather sign in to an existing account comes back to the
 * reveal with the hound waiting.
 *
 * THE REVEAL IS CHOREOGRAPHED (web/js/reveal-fx.js, css/quiz.css): silhouette, the hound, its name, its rules (R2, under 2.4 s),
 * then the ticket flip of "Would have bet today" with its "{n} of {m} games fit" count (R4). Content is in the page from the
 * first frame; the motion is `data-reveal` attributes. A tap skips it, reduced motion gets the final state.
 *
 * Written against attributes only (no classList, no dataset, no innerHTML): it must run in the node test harness's small DOM.
 */

