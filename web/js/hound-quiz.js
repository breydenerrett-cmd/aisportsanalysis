function saveSpec() {
  const spec = clone(S.result.spec);
  if (S.nameTouched && S.name.trim()) spec.name = S.name.trim();
  if (S.tagline.trim()) spec.tagline = S.tagline.trim();
  return spec;
}

/** Save the hound under the signed-in account (POST /hounds, then its look). Resolves true when it is kept, false when it is not. */
async function sendIn() {
  if (S.saved) return true;
  if (S.saving || !S.result) return false;
  setMessage("");
  S.problems = [];
  if (!getToken()) {
    stashForSignIn();
    showSignin("Sign in to keep your hound. Your quiz is saved on this device, so nothing is lost.");
    return false;
  }
  S.saving = true;
  q("reveal-save").disabled = true;
  try {
    const res = await apiPost("/hounds", { spec: saveSpec() });
    const hound = res.hound || {};
    S.saved = { id: hound.id, name: hound.name || saveSpec().name };
    // the look is the person's pick; best effort, the hound is in either way
    if (hound.id && S.result.look) { try { await put(`/hounds/${encodeURIComponent(hound.id)}/look`, { look: S.result.look }); } catch (err) { /* cosmetic */ } }
    S.pendingSave = false;
    clearDraft();
    renderSaved();
    celebrate(q("reveal-dog"), "created");
    // R6 starts here: this browser now watches this hound for its first graded ticket (web/js/first-grade.js)
    if (hound.id) watchFirstGrade(hound.id);
    syncKeep();
    return true;
  } catch (err) {
    handleSaveError(err);
    return false;
  } finally {
    S.saving = false;
    q("reveal-save").disabled = !!S.saved;
  }
}

function renderSaved() {
  const box = clearNode(q("reveal-message"));
  box.appendChild(h("div", { class: "qz-saved", "data-hook": "reveal-saved" }, [
    h("p", { class: "qz-bignum", text: `${S.saved.name} is in the kennel.` }),
    h("p", { class: "qz-fine", "data-hook": "reveal-saved-note", text: "Your record starts now. Every pick goes on the public record before the game." }),
    h("p", { class: "qz-actions" }, [
      S.saved.id ? h("a", { class: "qz-btn qz-btn--primary", href: houndHref(S.saved.id), "data-hook": "reveal-saved-link", text: "See your hound" }) : null,
      h("a", { class: "qz-btn qz-btn--ghost", href: "kennel.html", "data-hook": "reveal-kennel-link", text: "Open my kennel" })])]));
  q("reveal-save").disabled = true;
}

function setMessage(text, kind) {
  const box = clearNode(q("reveal-message"));
  if (text) box.appendChild(h("p", { class: `qz-msg qz-msg--${kind || "bad"}`, "data-hook": "reveal-error", text }));
}

function handleSaveError(err) {
  const status = err && err.status;
  const detail = err && err.detail;
  if (status === 401 || status === 403) {
    stashForSignIn();
    showSignin("Your sign-in has lapsed, or this account cannot build yet. Your quiz is saved on this device.");
  } else if (status === 422 && detail && detail.fields) {
    setMessage("The builder refused part of that: " + Object.entries(detail.fields).map(([k, v]) => `${k}: ${v}`).join("; "));
  } else if (status === 409) {
    setMessage(detail && detail.message ? detail.message : "You already have the most hounds running. Retire one first.");
  } else if (status === 429) {
    setMessage("Slow down a little and try again in a minute.");
  } else setMessage(describeError(err, "your hound").text);
}

function editRules() {
  if (!S.result) return;
  const spec = saveSpec();
  try {
    const ls = storage();
    if (ls) ls.setItem(HANDOFF_KEY, JSON.stringify({ spec, sentences: (S.result.sentences || []).concat(S.result.global_sentences || []), at: Date.now() }));
  } catch (err) { /* the builder then opens blank, which is still the builder */ }
  persist();
  window.location.href = `${BUILDER_HREF}?quiz=1`;
}

