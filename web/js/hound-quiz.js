function libraryError(err) {
  show("quiz");
  const stage = clearNode(q("quiz-stage"));
  stage.appendChild(h("section", { class: "qz-step", "data-hook": "quiz-error" }, [
    h("h1", { class: "qz-q", text: "The quiz is not loading." }),
    h("p", { class: "qz-sub", text: describeError(err, "the quiz library").text }),
    h("p", { class: "qz-actions" }, [
      h("button", { type: "button", class: "qz-btn qz-btn--primary", "data-hook": "quiz-retry", text: "Try again", on: { click: () => { boot(); } } }),
      h("a", { class: "qz-btn qz-btn--ghost", href: BUILDER_HREF, text: "Open the builder instead" })])]));
}

async function boot() {
  const params = new URLSearchParams(location.search);
  if (!S.bound) {
    S.bound = true;
    q("quiz-next").addEventListener("click", () => go(1));
    q("quiz-back").addEventListener("click", () => go(-1));
    q("quiz-restart").addEventListener("click", () => { resetAll(); S.dir = "back"; startQuiz(); });
  }
  try {
    S.lib = await apiGet("/hounds/quiz/library");
  } catch (err) {
    libraryError(err);
    return;
  }
  if (params.get("restart")) clearDraft();
  const draft = readDraft();
  if (draft) { restore(draft); S.resumed = true; }
  if (draft && draft.pendingSave && draft.stage === "reveal" && getToken()) {
    S.resumed = true;
    showReveal();
    setMessage("You are signed in. Your hound is ready to send in.", "ok");
    return;
  }
  // A saved quiz opens at the step it was left on; a new one opens at the first. There is no intro screen: the landing page explains it.
  S.dir = "fwd";
  startQuiz();
}

/** Resolves when the quiz has loaded its library and drawn the first screen (the tests wait for it). */
export const booted = q("quiz-app") ? boot() : Promise.resolve();
