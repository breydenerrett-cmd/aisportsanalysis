function hasAnyAnswer() {
  const a = S.answers;
  return !!(a.sports.length || a.markets.length || a.personality || a.bets_per_day || a.stake || a.price_comfort || a.timing
    || a.archetypes.length || a.quirks.length || a.look.coat || a.look.accessory);
}

function answered(stepId) {
  const a = S.answers;
  switch (stepId) {
    case "sports": return a.sports.length > 0;
    case "markets": return a.markets.length > 0;
    case "personality": return !!a.personality;
    case "risk": return !!(a.bets_per_day || a.stake || a.price_comfort);
    case "timing": return !!a.timing;
    case "archetypes": return a.archetypes.length > 0;
    case "quirks": return a.quirks.length > 0;
    case "look": return !!(a.look.coat || a.look.accessory);
    default: return false;
  }
}

function clearStep(stepId) {
  const a = S.answers;
  if (stepId === "sports") a.sports = [];
  else if (stepId === "markets") a.markets = [];
  else if (stepId === "personality") a.personality = null;
  else if (stepId === "risk") { a.bets_per_day = null; a.stake = null; a.price_comfort = null; }
  else if (stepId === "timing") a.timing = null;
  else if (stepId === "archetypes") a.archetypes = [];
  else if (stepId === "quirks") { a.quirks = []; a.letter = null; }
  else if (stepId === "look") a.look = { coat: null, accessory: null };
}

