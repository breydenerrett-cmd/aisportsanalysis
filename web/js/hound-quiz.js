function renderStep() {
  const step = STEPS[S.step];
  const stage = clearNode(q("quiz-stage"));
  stage.setAttribute("data-dir", S.dir);
  const body = STEP_BUILDERS[step.id]();
  const section = h("section", { class: "qz-step", "data-hook": "quiz-step-body", "data-step": step.id, "aria-labelledby": "qz-q" }, [
    h("p", { class: "qz-eyebrow", text: `Question ${S.step + 1} of ${STEPS.length}` }),
    h("h1", { id: "qz-q", class: "qz-q", tabindex: "-1", "data-hook": "quiz-question", text: step.title }),
    h("p", { class: "qz-sub", text: step.sub }), body]);
  stage.appendChild(section);
  syncBar();
  if (typeof window.scrollTo === "function") window.scrollTo(0, 0);
  if (step.id === "archetypes") { S.moves = null; loadMoves(0); }       // fresh for the answers so far, every time the question opens
  const heading = q("quiz-question");
  if (heading && typeof heading.focus === "function") heading.focus();
}

/** Keep the pressed state of every card in step with the answers without rebuilding (so nothing re-animates). */
function sync() {
  const nodes = document.querySelectorAll("[data-group]");
  for (const n of nodes) {
    const group = n.getAttribute("data-group"), id = n.getAttribute("data-id");
    const value = group === "bets_per_day" ? Number(id) : group === "stake" ? Number(id) : id;
    n.setAttribute("aria-pressed", selected(group, value) ? "true" : "false");
  }
  const letters = q("quiz-letters");
  if (letters) { if (S.answers.quirks.includes("lucky_letter")) letters.removeAttribute("hidden"); else letters.setAttribute("hidden", ""); }
  const tray = q("quiz-tray");
  if (tray) swap(tray, trayNode());
  syncBar();
}

function syncBar() {
  const last = S.step === STEPS.length - 1;
  const step = STEPS[S.step];
  const next = q("quiz-next");
  if (!next) return;
  const picks = S.answers.archetypes.length;
  next.textContent = last ? "Reveal my hound" : step.id === "archetypes" && picks ? `Next (${picks} of ${(S.lib.limits && S.lib.limits.archetype_picks) || 2})` : "Next";
  next.disabled = !answered(step.id);
  q("quiz-skip").textContent = last ? "Skip and reveal" : "Skip";
  const done = STEPS.filter((s) => answered(s.id)).length;
  const bar = q("quiz-progress");
  const pct = Math.round((S.step / STEPS.length) * 100);
  bar.setAttribute("style", `--p:${pct}%`);
  bar.setAttribute("aria-valuenow", String(S.step));
  q("quiz-step").textContent = `Question ${S.step + 1} of ${STEPS.length}` + (done ? ` · ${done} answered` : "");
}

function go(delta) {
  const target = S.step + delta;
  if (target < 0) { showIntro(); return; }
  if (target >= STEPS.length) { showReveal(); return; }
  S.dir = delta > 0 ? "fwd" : "back";
  S.step = target;
  persist();
  renderStep();
}

function skip() {
  clearStep(STEPS[S.step].id);
  persist();
  go(1);
}

