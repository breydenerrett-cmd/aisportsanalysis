// ---- the draft (localStorage, every touch guarded) ------------------------------------------------------------------

function storage() {
  try { return window.localStorage || null; } catch (err) { return null; }
}

export function readDraft() {
  try {
    const ls = storage();
    const raw = ls && ls.getItem(DRAFT_KEY);
    if (!raw) return null;
    const d = JSON.parse(raw);
    return d && d.v === 1 && d.answers && typeof d.answers === "object" ? d : null;
  } catch (err) { return null; }
}

function persist() {
  try {
    const ls = storage();
    if (!ls) return;
    if (!hasAnyAnswer() && !S.english.text && !S.nameTouched) { ls.removeItem(DRAFT_KEY); return; }
    ls.setItem(DRAFT_KEY, JSON.stringify({ v: 1, answers: S.answers, step: S.step, stage: S.stage === "reveal" ? "reveal" : "quiz",
      name: S.nameTouched ? S.name : "", tagline: S.tagline, english: { text: S.english.text, draft: S.english.draft },
      pendingSave: S.pendingSave, savedAt: Date.now() }));
  } catch (err) { /* a full or blocked store: no resume, nothing else */ }
}

function clearDraft() {
  try { const ls = storage(); if (ls) ls.removeItem(DRAFT_KEY); } catch (err) { /* nothing to clear */ }
}

/** Put a saved draft back. A draft from the eight-question quiz carries answers this one no longer asks; only the four it asks are read. */
function restore(d) {
  const base = blankAnswers();
  const a = d.answers || {};
  if (Array.isArray(a.sports)) base.sports = a.sports.filter((x) => typeof x === "string");
  if (typeof a.personality === "string") base.personality = a.personality;
  if (typeof a.risk === "string") base.risk = a.risk;
  base.look = Object.assign({ coat: null, accessory: null }, a.look && typeof a.look === "object" ? a.look : {});
  S.answers = base;
  S.step = Number.isInteger(d.step) && d.step >= 0 && d.step < STEPS.length ? d.step : 0;
  S.name = typeof d.name === "string" ? d.name : "";
  S.nameTouched = !!S.name;
  S.tagline = typeof d.tagline === "string" ? d.tagline : "";
  const e = d.english || {};
  S.english = { text: typeof e.text === "string" ? e.text : "", draft: e.draft && typeof e.draft === "object" ? e.draft : null,
    understood: [], notRead: [], assumed: [] };
  S.pendingSave = !!d.pendingSave;
}

// ---- answers ------------------------------------------------------------------------------------------------------------

function hasAnyAnswer() {
  const a = S.answers;
  return !!(a.sports.length || a.personality || a.risk !== DEFAULT_RISK || a.look.coat || a.look.accessory);
}

function answered(stepId) {
  const a = S.answers;
  switch (stepId) {
    case "sports": return a.sports.length > 0;
    case "personality": return !!a.personality;
    case "risk": return !!a.risk;
    default: return true;                        // name and look are optional
  }
}

function persona(id) {
  return S.lib ? (S.lib.personalities || []).find((p) => p.id === id) || null : null;
}

/** The three risk answers derived from the one risk choice: a bets-a-day cap, a stake and (unless the style owns its prices) a price band.
 *  A chalk or underdog style already IS a price band, so the risk choice does not fight it: it sets the stake and the cap only. */
export function riskAnswers(lib = S.lib, riskId = S.answers.risk, personalityId = S.answers.personality) {
  const level = lib && (lib.risk_levels || []).find((r) => r.id === riskId);
  if (!level) return {};
  const out = { bets_per_day: level.bets_per_day, stake: level.stake };
  const p = lib.personalities && lib.personalities.find((x) => x.id === personalityId);
  const owns = !!p && (p.stance === "chalk" || p.stance === "dog");
  if (!owns && !(p && p.style === GEMATRIA_STYLE)) out.price_comfort = level.price_comfort;
  return out;
}

/** The body of POST /hounds/quiz/compose's `answers`: the four answers, plus the defaults derived from them. */
export function answersPayload() {
  const a = S.answers, out = {};
  if (a.sports.length) out.sports = a.sports.slice();
  if (a.personality) out.personality = a.personality;
  out.markets = DEFAULT_MARKETS.slice();
  Object.assign(out, riskAnswers());
  const look = {};
  if (a.look.coat) look.coat = a.look.coat;
  if (a.look.accessory) look.accessory = a.look.accessory;
  if (Object.keys(look).length) out.look = look;
  if (S.nameTouched && S.name.trim()) out.name = S.name.trim();
  if (S.tagline.trim()) out.tagline = S.tagline.trim();
  return out;
}

function selected(group, id) {
  const a = S.answers;
  switch (group) {
    case "sports": return a.sports.includes(id);
    case "personality": return a.personality === id;
    case "risk": return a.risk === id;
    case "coat": return a.look.coat === id;
    case "accessory": return a.look.accessory === id;
    default: return false;
  }
}

function toggle(group, id) {
  const a = S.answers;
  S.notice = "";
  if (group === "sports") {
    // "All sports" and a list of sports are two different answers: picking one clears the other
    if (id === ANY) a.sports = a.sports.includes(ANY) ? [] : [ANY];
    else {
      const base = a.sports.filter((x) => x !== ANY);
      a.sports = base.includes(id) ? base.filter((x) => x !== id) : base.concat([id]);
    }
  } else if (group === "coat") a.look.coat = a.look.coat === id ? null : id;
  else if (group === "accessory") a.look.accessory = a.look.accessory === id ? null : id;
  else if (group === "personality") a.personality = a.personality === id ? null : id;
  else if (group === "risk") a.risk = id;
  persist();
  sync();
  if (group === "coat" || group === "accessory") refreshLook();
  if (group === "personality" || group === "risk") refreshRiskNote();
}

