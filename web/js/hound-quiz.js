async function backtest() {
  if (S.drillBusy || !S.result) return;
  const out = clearNode(q("reveal-backtest-result"));
  if (S.result.spec && S.result.spec.style === GEMATRIA_STYLE) {
    // the house Gematria Hound is forward-only and so is a hound of its style: no replay is offered (the server refuses one too)
    out.appendChild(h("p", { class: "qz-fine", "data-hook": "reveal-backtest-note", text: "A Gematria hound is forward-only. It weighs each game once, "
      + "an hour before the start, so a past day cannot be replayed." }));
    return;
  }
  if (!getToken()) {
    stashForSignIn();
    showSignin("Sign in to run a backtest. Your quiz is saved on this device.");
    return;
  }
  S.drillBusy = true;
  q("reveal-backtest-go").disabled = true;
  out.appendChild(h("p", { class: "qz-fine", text: `Replaying ${BACKTEST_DAYS} days of boards. This can take up to a minute.` }));
  try {
    const res = await post("/hounds/drill", { spec: previewSpec(), days: BACKTEST_DAYS }, SLOW_MS);
    S.drill = res;
    clearNode(out);
    const r = res.record || {};
    const units = typeof res.units_average_price === "number" ? `${res.units_average_price > 0 ? "+" : ""}${res.units_average_price.toFixed(2)}u at the average price` : "units not reported";
    out.appendChild(h("p", { class: "qz-drill__label", "data-hook": "reveal-backtest-label", text: res.label || "Hindsight drill: not counted" }));
    out.appendChild(h("p", { class: "qz-bignum", "data-hook": "reveal-backtest-record",
      text: r.bets ? `${r.wins}-${r.losses}${r.pushes ? `-${r.pushes}` : ""} over ${r.bets} ${r.bets === 1 ? "bet" : "bets"}, ${units}` : "No bets in that window." }));
    if (res.sample_note) out.appendChild(h("p", { class: "qz-fine", "data-hook": "reveal-backtest-note", text: res.sample_note }));
    if (res.disclosure) out.appendChild(h("p", { class: "qz-fine", text: res.disclosure }));
  } catch (err) {
    clearNode(out);
    if (err && (err.status === 401 || err.status === 403)) { stashForSignIn(); showSignin("Sign in to run a backtest. Your quiz is saved on this device."); }
    // A FREE account is refused with 402 upgrade_required: Backtest is a member tool. The same prompt as the builder,
    // Ask and Live (upgrade.js), not a plain error line, so the person is told what the plan is and where it is.
    else if (showUpgrade(out, err)) { /* the member prompt replaced the contents of `out` */ }
    else out.appendChild(h("p", { class: "qz-fine qz-fine--bad", "data-hook": "reveal-backtest-error",
      text: err && err.status === 429 ? "Another backtest is running. Try again in a moment." : errorText(err, "The backtest did not run.") }));
  } finally {
    S.drillBusy = false;
    q("reveal-backtest-go").disabled = false;
  }
}

