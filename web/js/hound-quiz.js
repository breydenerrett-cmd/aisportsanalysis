async function addEnglish() {
  const text = String(q("reveal-english-input").value || "").trim();
  const status = q("reveal-english-status");
  if (!text) { status.textContent = "Type something first."; return; }
  status.textContent = "Reading...";
  let res;
  try {
    res = await apiPost("/hounds/english", { text });
  } catch (err) {
    status.textContent = err && err.status === 429 ? "Slow down a little; try again in a minute." : describeError(err, "the reader").text;
    return;
  }
  status.textContent = "";
  S.english = { text, draft: res.draft && res.draft.rules && res.draft.rules.length ? res.draft : null,
    understood: res.understood || [], notRead: res.not_understood || [], assumed: res.assumed || [] };
  const read = q("reveal-english-read");
  read.hidden = false;
  const ok = clearNode(q("reveal-english-understood"));
  for (const u of S.english.understood) ok.appendChild(h("li", {}, [h("strong", { text: `"${u.text}"` }), ` is read as: ${u.meaning}`]));
  if (!S.english.understood.length) ok.appendChild(h("li", { class: "qz-fine", text: "Nothing in that matched a rule yet." }));
  const bad = clearNode(q("reveal-english-notread"));
  for (const n of S.english.notRead) bad.appendChild(h("li", {}, [h("strong", { text: n.text ? `"${n.text}"` : "Something" }), ` was not understood: ${n.reason}`]));
  if (S.english.notRead.length) bad.appendChild(h("li", { class: "qz-fine", text: "Open Edit rules to add that by hand." }));
  persist();
  if (S.english.draft) compose();
}

