function renderStep() {
  const step = STEPS[S.step];
  const stage = clearNode(q("quiz-stage"));
  stage.setAttribute("data-dir", S.dir);
  const body = STEP_BUILDERS[step.id]();
  const section = h("section", { class: "qz-step", "data-hook": "quiz-step-body", "data-step": step.id, "aria-labelledby": "qz-q" }, [
    h("h1", { id: "qz-q", class: "qz-q", tabindex: "-1", "data-hook": "quiz-question", text: step.title }),
    h("p", { class: "qz-sub", text: step.sub }), body]);
  if (S.resumed && S.step === 0 && hasAnyAnswer()) {
    section.appendChild(h("p", { class: "qz-fine", role: "status", "data-hook": "quiz-welcome", text: "Welcome back. Your quiz was saved on this device." }));
  }
  stage.appendChild(section);
  syncBar();
  if (typeof window.scrollTo === "function") window.scrollTo(0, 0);
  const heading = q("quiz-question");
  if (heading && typeof heading.focus === "function") heading.focus();
}

/** Keep the pressed state of every card in step with the answers without rebuilding (so nothing re-animates). */
function sync() {
  const nodes = document.querySelectorAll("[data-group]");
  for (const n of nodes) n.setAttribute("aria-pressed", selected(n.getAttribute("data-group"), n.getAttribute("data-id")) ? "true" : "false");
  syncBar();
}

function syncBar() {
  const last = S.step === STEPS.length - 1;
  const step = STEPS[S.step];
  const next = q("quiz-next");
  if (!next) return;
  next.textContent = last ? "Meet my hound" : "Next";
  next.disabled = !answered(step.id);
  q("quiz-back").hidden = S.step === 0;
  const restart = q("quiz-restart");
  if (restart) restart.hidden = !(hasAnyAnswer() || S.nameTouched);
  const bar = q("quiz-progress");
  const pct = Math.round(((S.step + 1) / STEPS.length) * 100);
  bar.setAttribute("style", `--p:${pct}%`);
  bar.setAttribute("aria-valuenow", String(S.step + 1));
  bar.setAttribute("aria-valuemax", String(STEPS.length));
  q("quiz-step").textContent = `Step ${S.step + 1} of ${STEPS.length}`;
}

function go(delta) {
  const target = S.step + delta;
  if (target < 0) return;
  if (target >= STEPS.length) { showReveal(); return; }
  S.dir = delta > 0 ? "fwd" : "back";
  S.step = target;
  persist();
  renderStep();
}

function show(which) {
  q("quiz-shell").hidden = which !== "quiz";
  q("quiz-reveal").hidden = which !== "reveal";
  const noscript = q("quiz-noscript");
  if (noscript) noscript.hidden = true;
}

function startQuiz() {
  show("quiz");
  S.stage = "quiz";
  renderStep();
}

function resetAll() {
  S.answers = blankAnswers();
  S.name = ""; S.nameTouched = false; S.tagline = ""; S.shownName = "";
  S.english = { text: "", draft: null, understood: [], notRead: [], assumed: [] };
  S.result = null; S.preview = null; S.drill = null; S.saved = null; S.pendingSave = false; S.problems = []; S.moreSports = false;
  S.personalityTouched = false; S.personalityPage = 0; S.step = 0; S.resumed = false;
  S.previewSettled = false;
  clearDraft();
}

// ---- the reveal -----------------------------------------------------------------------------------------------------------

function showReveal() {
  S.stage = "reveal";
  S.step = STEPS.length - 1;
  persist();
  show("reveal");
  if (typeof window.scrollTo === "function") window.scrollTo(0, 0);
  buildReveal();
  compose();
}

async function compose() {
  const seq = ++S.seq;
  S.composing = true;
  S.composeError = "";
  renderResult();
  const body = { answers: answersPayload() };
  if (S.english.draft) body.english_draft = S.english.draft;
  try {
    const res = await apiPost("/hounds/quiz/compose", body);
    if (seq !== S.seq) return;
    S.result = res;
    if (!S.nameTouched) S.shownName = res.spec.name;
    S.composing = false;
    renderResult();
    persist();
    loadPreview();
    if (!S.celebrated) { S.celebrated = true; celebrate(q("reveal-dog"), "quiz"); }
  } catch (err) {
    if (seq !== S.seq) return;
    S.composing = false;
    S.composeError = err && err.status === 429 ? "Slow down a little and try again in a minute." : describeError(err, "the quiz").text;
    renderResult();
  }
}

